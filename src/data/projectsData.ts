export function getProjectImageUrl(image?: string): string {
  if (!image) {
    return '/empire-group-project-2560x1440.jpg';
  }
  if (image.startsWith('http://') || image.startsWith('https://') || image.startsWith('/')) {
    return image;
  }
  // Local high-res assets when available
  if (image === 'kolte-patil-life-republic-hinjewadi.jpg') {
    return '/empire-group-project-2560x1440.jpg';
  }
  if (image === 'blue-ridge-hinjewadi-pune.jpg') {
    return '/Blue%20ridge.png';
  }
  if (image === 'puneville.jpg') {
    return '/Pune%20Villey.png';
  }
  return `https://www.empiireprojects.in/_next/image?url=%2Fprojects%2Fcompleted%2F${image}&w=828&q=75`;
}

